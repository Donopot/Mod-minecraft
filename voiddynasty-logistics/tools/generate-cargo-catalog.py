"""Generate both adapters' fixed mission catalogue from our own contract data."""
import hashlib
import json
from bridge_project import BRIDGE
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
def main():
    data=json.loads((ROOT/'protocol/cargo-missions.v1.json').read_text(encoding='utf-8'))
    canonical=json.dumps(data,sort_keys=True,separators=(',',':'),ensure_ascii=False)
    digest=hashlib.sha256(canonical.encode()).hexdigest()
    rows=data['missions'];assert len({r['mission_id'] for r in rows})==len(rows)
    def quoted(s):return json.dumps(s,ensure_ascii=True)
    cs='''// Generated by tools/generate-cargo-catalog.py. Edit the JSON contract.
using System;
using System.IO;
namespace VoidDynasty.RogueTrader {
    public sealed class CargoMission {
        public readonly string Id,Label,Origin,Item,Blueprint,Material;
        public readonly int Count;
        public CargoMission(string id,string label,string origin,string item,int count,string blueprint,string material){Id=id;Label=label;Origin=origin;Item=item;Count=count;Blueprint=blueprint;Material=material;}
    }
    public static class CargoCatalog {
        public const string Hash="HASH";
        public const string Default="logistics_first_delivery";
        public static readonly CargoMission[] All=new CargoMission[]{
'''.replace('HASH',digest)
    java='''// Generated by tools/generate-cargo-catalog.py. Edit the JSON contract.
package com.donopot.voiddynastybridge;
import java.util.List;
public final class CargoCatalog {
    public record Mission(String id,String label,String origin,String item,int count,String blueprint,String material){}
    public static final String HASH="HASH_VALUE",DEFAULT="logistics_first_delivery";
    public static final List<Mission> ALL=List.of(
'''.replace('HASH_VALUE',digest)
    for i,r in enumerate(rows):
        args=','.join([quoted(r[k]) for k in ['mission_id','label','rt_origin','item_id']]+[str(r['count']),quoted(r['cargo_blueprint_id']),quoted(r['item_label'])])
        cs+='            new CargoMission('+args+'),\n'
        java+='        new Mission('+args+')'+(',' if i<len(rows)-1 else '')+'\n'
    cs+='''        };
        public static CargoMission Get(string id){foreach(var m in All)if(m.Id==id)return m;throw new InvalidDataException("MISSION_MISMATCH");}
    }
}
'''
    java+='''    );
    public static Mission get(String id){return ALL.stream().filter(m->m.id().equals(id)).findFirst().orElseThrow(()->new IllegalArgumentException("Mission inconnue"));}
    public static boolean accepts(String item){return ALL.stream().anyMatch(m->m.item().equals(item));}
}
'''
    (ROOT/'rt-adapter/CargoCatalog.cs').write_text(cs,encoding='utf-8')
    (BRIDGE/'src/main/java/com/donopot/voiddynastybridge/CargoCatalog.java').write_text(java,encoding='utf-8')
    print('Generated',len(rows),'missions; catalogue SHA-256:',digest)
if __name__=='__main__':main()
